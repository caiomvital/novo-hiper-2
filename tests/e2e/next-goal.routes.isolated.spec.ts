import { expect, test } from '@playwright/test';
import { login, openAdventure } from './helpers';
test.use({hasTouch:true,viewport:{width:844,height:390}});
test('história concluída orienta compra e depois instalação usando preço e saldo oficiais',async({page})=>{
 test.setTimeout(180_000);
 await login(page,{filterOrders:false});
 await page.request.post('/api/plants',{data:{id:'e2e_next_goal',name:'Planta da próxima conquista',price:80,stock_quantity:3,image_path:'/pwa-192x192.png'}});
 const story=await(await page.request.post('/api/progress/stories/cantinho_maria/accept')).json();
 const delivery=await(await page.request.post('/api/deliveries/start',{data:{order_id:story.orderId}})).json();
 expect((await page.request.post(`/api/deliveries/${delivery.id}/finish`)).ok()).toBe(true);
 expect((await page.request.post('/api/progress/stories/cantinho_maria/ack')).ok()).toBe(true);
 await page.reload();await openAdventure(page);
 await page.locator('#btn-mission-details').click();
 const goal=page.locator('#journey-next-goal');
 await expect(goal).toBeVisible();
 const shop=await(await page.request.get('/api/shop')).json();
 const upgrade=shop.upgrades.find((u:any)=>u.state==='available');
 await expect(goal).toHaveAttribute('data-upgrade',upgrade.id);
 await expect(goal).toContainText('Placa de madeira');
 await expect(goal).toContainText('60,00');await expect(goal).toContainText('80,00');
 await page.screenshot({path:'docs/evidence/mobile-landscape/next-goal.png'});
 await page.locator('#btn-next-goal-guide').click();
 await expect(page.locator('#btn-mission-details')).toHaveAttribute('aria-expanded','false');
 await page.waitForFunction(()=>window.__NH_ADVENTURE__?.getState().delivery?.indicator?.name==='Loja de Utilidades');
 expect((await(await page.request.get('/api/cash')).json()).balance).toBe(shop.balance);
 expect((await page.request.post(`/api/shop/upgrades/${upgrade.id}/purchase`)).ok()).toBe(true);
 await page.evaluate(()=>window.dispatchEvent(new Event('focus')));
 await page.locator('#btn-mission-details').click();
 await expect(goal).toContainText('Você já comprou esta melhoria');
 await expect(page.locator('#btn-next-goal-guide')).toHaveText('Ir ao balcão instalar');
 await page.locator('#btn-next-goal-guide').click();
 await page.waitForFunction(()=>window.__NH_ADVENTURE__?.getState().delivery?.indicator?.name==='Novo Hiper');
 expect((await(await page.request.get('/api/cash')).json()).balance).toBe(shop.balance-upgrade.price);
});
