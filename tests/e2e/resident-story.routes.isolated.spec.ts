import { expect, test } from '@playwright/test';
import { login, openAdventure, pickUpActiveOrder, runToGoal, state, teleport, waitForScene } from './helpers';
import { ROSTER } from '../../src/shared/roster';
import { resolveDestination } from '../../src/phaser-game/config/houseCatalog';

test.use({ viewport: { width: 480, height: 650 }, hasTouch: true });
test('Dona Maria apresenta o cantinho, recebe a planta do catálogo e conserva o jardim após recarregar', async ({ page }) => {
  test.setTimeout(300_000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await login(page, { filterOrders: false });
  const p = await (await page.request.post('/api/plants', { data: { id: 'e2e_planta_do_cantinho', name: 'Camomila do meu jardim', price: 28.5, stock_quantity: 3, image_path: '/pwa-192x192.png' } })).json();
  await page.reload(); await openAdventure(page);
  await page.locator('#btn-adventure-fullscreen').click();
  await page.waitForFunction(() => Boolean(document.fullscreenElement));
  const destination = resolveDestination(ROSTER.find(r => r.id === 'cust_dona_maria')!.destinationId);
  if (destination.status !== 'house') throw new Error('Casa de Dona Maria ausente');
  const spot = destination.house.deliveryPoint;
  await teleport(page, spot.x, spot.y + 36);
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().residentGarden?.npcVisible);
  expect((await state(page)).residentGarden!.planted).toBe(false);
  await page.screenshot({ path: 'docs/evidence/resident-story/01-cantinho-vazio.png' });
  await page.keyboard.press('KeyE');
  await expect(page.locator('#resident-story-modal')).toBeVisible();
  await expect(page.locator('#resident-story-modal')).toContainText('a entrada da minha casa está tão vazia');
  await page.screenshot({ path: 'docs/evidence/resident-story/02-conversa.png' });
  await page.locator('#btn-accept-resident-story').click();
  await expect(page.locator('#resident-story-modal')).toContainText('Camomila do meu jardim');
  await page.locator('#btn-close-resident-story').click();
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().delivery?.customerName === 'Dona Maria');
  const first = (await (await page.request.get('/api/progress')).json()).residentStory;
  expect(first.status).toBe('ordered');
  expect((await (await page.request.get('/api/cash')).json()).balance).toBe(0);
  await pickUpActiveOrder(page);
  await page.locator('#btn-start-delivery-route').click(); await waitForScene(page, 'platform');
  await page.setViewportSize({ width: 480, height: 360 });
  await runToGoal(page, 120_000);
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().platform?.confirmationVisible);
  await page.keyboard.press('Enter'); await waitForScene(page, 'world');
  expect((await (await page.request.get('/api/progress')).json()).residentStory.status).toBe('ordered');
  expect((await (await page.request.get('/api/cash')).json()).balance).toBe(0);
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().delivery?.near);
  await page.keyboard.press('KeyE');
  await page.setViewportSize({ width: 480, height: 650 });
  await expect(page.locator('#resident-story-modal')).toBeVisible({ timeout: 20_000 });
  await expect(page.locator('#resident-story-modal')).toContainText('Foi a sua loja que começou esse jardim');
  await expect(page.locator('#resident-story-photo')).toHaveAttribute('src', p.image_path);
  await page.screenshot({ path: 'docs/evidence/resident-story/03-agradecimento.png' });
  await page.locator('#btn-finish-resident-story').click();
  await expect(page.locator('#resident-story-modal')).toHaveCount(0);
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().residentGarden?.planted);
  expect((await state(page)).residentGarden!.plantName).toBe('Camomila do meu jardim');
  await teleport(page, spot.x - 50, spot.y + 50);
  await page.screenshot({ path: 'docs/evidence/resident-story/04-cantinho-plantado.png' });
  const cash = await (await page.request.get('/api/cash')).json();
  expect(cash.balance).toBe(28.5);
  expect(cash.transactions.filter((t: any) => t.order_id === first.orderId)).toHaveLength(1);
  expect((await (await page.request.get(`/api/plants/${p.id}`)).json()).stock_quantity).toBe(2);
  await page.reload(); await openAdventure(page);
  await page.locator('#btn-adventure-fullscreen').click();
  await page.waitForFunction(() => Boolean(document.fullscreenElement));
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().residentGarden?.planted);
  await expect(page.locator('#resident-story-modal')).toHaveCount(0);
  await teleport(page, spot.x, spot.y + 36);
  await page.keyboard.press('KeyE');
  await expect(page.locator('#resident-story-modal')).toBeVisible();
  await expect(page.locator('#btn-accept-resident-story')).toHaveCount(0);
  await page.locator('#btn-finish-resident-story').click();
  expect((await (await page.request.get('/api/cash')).json()).balance).toBe(cash.balance);
  expect((await (await page.request.get(`/api/plants/${p.id}`)).json()).stock_quantity).toBe(2);
  expect(errors).toEqual([]);
});
