import { expect, test } from '@playwright/test';
import { enterStore, leaveStore, login, openAdventure, runToGoal, state, teleport, waitForScene } from './helpers';
import { PREP_BENCH, COUNTER } from '../../src/phaser-game/config/interiorMap';
import { WORLD_MAP } from '../../src/phaser-game/config/worldMap';

test.use({ viewport: { width: 480, height: 650 }, hasTouch: true });
test('foto e cadastro → pedido automático → vitrine → retirada → plataforma → venda única → melhoria', async ({ page }) => {
  test.setTimeout(360_000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await login(page, { filterOrders: false });
  await expect(page.locator('#shop-journey')).toContainText('Sua aventura começa com uma planta sua');
  await page.locator('#journey-records summary').click();
  await expect(page.locator('#journey-records')).toContainText('baixa o estoque');
  await page.screenshot({ path: 'docs/evidence/store-journey/01-comeco.png' });
  await page.locator('#btn-journey-next').click();
  await page.locator('#input-gallery-photo').setInputFiles('public/pwa-192x192.png');
  await expect(page.locator('#btn-save-plant')).toBeEnabled();
  await page.locator('#input-plant-name').fill('Manjericão do Bernardo');
  await page.locator('#input-plant-price').fill('150');
  await page.locator('#input-plant-stock').fill('3');
  await page.locator('#btn-save-plant').click();
  await expect(page.locator('#plant-form-container')).toHaveCount(0);
  await expect(page.locator('#journey-product')).toContainText('Manjericão do Bernardo');
  await expect(page.locator('#shop-journey')).toContainText('pediu Manjericão do Bernardo');
  const plants = await (await page.request.get('/api/plants')).json();
  const plant = plants.find((p: any) => p.name === 'Manjericão do Bernardo');
  expect(plant.image_path).toMatch(/^\/uploads\/plants\//);
  const orders = await (await page.request.get('/api/orders')).json();
  const order = orders.find((o: any) => o.status !== 'entregue');
  expect(order.items[0].plant_id).toBe(plant.id);
  expect(Number(order.total)).toBe(150);
  await page.screenshot({ path: 'docs/evidence/store-journey/02-pedido-da-minha-planta.png' });
  await page.locator('#btn-journey-next').click();
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().scene === 'world');
  await page.locator('#btn-adventure-fullscreen').click();
  await page.waitForFunction(() => Boolean(document.fullscreenElement));
  await expect(page.locator('#adventure-order-photo')).toHaveAttribute('src', plant.image_path);
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().delivery?.indicator?.name === 'Novo Hiper');
  await enterStore(page);
  await expect(page.locator('#store-vitrine')).toContainText('Manjericão do Bernardo');
  await expect(page.locator('#store-vitrine img')).toHaveAttribute('src', plant.image_path);
  await expect(page.locator('#store-vitrine')).toContainText('150,00');
  await page.screenshot({ path: 'docs/evidence/store-journey/03-vitrine-e-preparo.png' });
  await teleport(page, PREP_BENCH.interact.x, PREP_BENCH.interact.y);
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().delivery?.interior?.canPickup);
  await page.keyboard.press('KeyE');
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().delivery?.interior?.carrying);
  expect((await (await page.request.get(`/api/plants/${plant.id}`)).json()).stock_quantity).toBe(3);
  expect((await (await page.request.get('/api/cash')).json()).balance).toBe(0);
  // A retirada oficial sobrevive à recarga e a jornada retoma da entrega.
  await page.reload();
  await expect(page.locator('#shop-journey')).toContainText('A planta já está com Bernardo');
  await openAdventure(page);
  await page.locator('#btn-adventure-fullscreen').click();
  await page.waitForFunction(() => Boolean(document.fullscreenElement));
  await expect(page.locator('#btn-start-delivery-route')).toBeVisible();
  await page.locator('#btn-start-delivery-route').click();
  await waitForScene(page, 'platform');
  await page.setViewportSize({ width: 480, height: 360 });
  await runToGoal(page, 120_000);
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().platform?.confirmationVisible);
  await page.keyboard.press('Enter');
  await waitForScene(page, 'world');
  expect((await (await page.request.get('/api/cash')).json()).balance).toBe(0);
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().delivery?.near);
  await page.keyboard.press('KeyE');
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().delivery?.phase === 'done');
  await page.keyboard.press('KeyE');
  const cash = await (await page.request.get('/api/cash')).json();
  expect(cash.balance).toBe(150);
  expect(cash.transactions.filter((t: any) => t.order_id === order.id)).toHaveLength(1);
  expect((await (await page.request.get(`/api/plants/${plant.id}`)).json()).stock_quantity).toBe(2);
  await page.setViewportSize({ width: 480, height: 650 });
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().delivery?.indicator?.name === 'Novo Hiper');
  await page.screenshot({ path: 'docs/evidence/store-journey/04-volta-com-resultado.png' });
  await enterStore(page);
  await expect(page.locator('#store-vitrine')).toContainText('2 vaso(s)');
  await teleport(page, 320, 330); // afasta da porta para rearmar a saída
  await leaveStore(page);
  // A melhoria usa o saldo confirmado e precisa ser instalada na loja.
  await teleport(page, WORLD_MAP.utilities.interact.x, WORLD_MAP.utilities.interact.y);
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().delivery?.shop.nearUtilities);
  await page.keyboard.press('KeyE');
  await expect(page.locator('#shop-panel')).toBeVisible();
  await page.locator('#btn-shop-buy-placa_madeira').click();
  await page.locator('#btn-shop-guide-store').click();
  await enterStore(page);
  await teleport(page, COUNTER.interact.x, COUNTER.interact.y);
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().delivery?.interior?.nearCounter);
  await page.keyboard.press('KeyE');
  await expect(page.locator('#btn-shop-install-placa_madeira')).toBeVisible();
  await page.locator('#btn-shop-install-placa_madeira').click();
  expect((await (await page.request.get('/api/shop')).json()).upgrades.find((u: any) => u.id === 'placa_madeira').state).toBe('installed');
  expect((await (await page.request.get('/api/cash')).json()).balance).toBe(90);
  await leaveStore(page);
  await page.screenshot({ path: 'docs/evidence/store-journey/05-loja-melhorada.png' });
  if (await page.evaluate(() => Boolean(document.fullscreenElement))) await page.evaluate(() => document.exitFullscreen());
  await page.locator('#tab-btn-catalog').click();
  await expect(page.locator('#journey-last-sale')).toContainText('Manjericão do Bernardo');
  await page.locator('#btn-journey-cash').click();
  await expect(page.locator('#cash-register-modal-container')).toBeVisible();
  expect(errors).toEqual([]);
});
