import { expect, test } from '@playwright/test';
import { closeSuiteOrders, createSuiteOrder, suiteId } from './suiteData';
import { enterStore, holdKeys, leaveStore, login, openAdventure, state, teleport } from './helpers';
import { COUNTER, PREP_BENCH } from '../../src/phaser-game/config/interiorMap';
import { TOPDOWN_BODY } from '../../src/phaser-game/config/topdownSpriteConfig';

test.use({ viewport: { width: 740, height: 580 }, hasTouch: true });
test('interior com volume: circulação, colisão do balcão e retirada real em tela pequena', async ({ page }) => {
  test.setTimeout(120_000);
  await login(page); await closeSuiteOrders(page);
  const plant = await (await page.request.post('/api/plants', { data: { id: suiteId('interior-art'), name: 'Planta do novo interior', price: 80, stock_quantity: 5, image_path: '/pwa-192x192.png' } })).json();
  const order = await createSuiteOrder(page, { plantId: plant.id });
  const cash = await (await page.request.get('/api/cash')).json();
  await openAdventure(page); await page.locator('#btn-adventure-fullscreen').click();
  await page.waitForFunction(() => Boolean(document.fullscreenElement));
  await enterStore(page);
  await teleport(page, 350, 195); await holdKeys(page, ['ArrowDown'], 400);
  expect((await state(page)).player!.y + TOPDOWN_BODY.height / 2).toBeLessThanOrEqual(COUNTER.rect.y + 2);
  await page.screenshot({ path: 'docs/evidence/interior-art/balcao-por-tras.png' });
  await teleport(page, COUNTER.interact.x, COUNTER.interact.y); await holdKeys(page, ['ArrowUp'], 400);
  expect((await state(page)).player!.y - TOPDOWN_BODY.height / 2).toBeGreaterThanOrEqual(COUNTER.rect.y + COUNTER.rect.h - 2);
  await page.screenshot({ path: 'docs/evidence/interior-art/interior-geral.png' });
  await page.setViewportSize({ width: 480, height: 500 });
  await teleport(page, PREP_BENCH.interact.x, PREP_BENCH.interact.y);
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().delivery?.interior?.canPickup);
  await page.keyboard.press('KeyE');
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().delivery?.interior?.carrying);
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().camera?.width === 480);
  const small = await state(page);
  const bounds = small.delivery!.interior!.promptBounds!;
  expect(bounds.x).toBeGreaterThanOrEqual(0);
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(small.camera!.width + 1);
  expect(bounds.y).toBeGreaterThanOrEqual(0);
  expect(bounds.y + bounds.height).toBeLessThan(small.camera!.height - 170);
  await page.screenshot({ path: 'docs/evidence/interior-art/preparo-celular.png' });
  expect((await (await page.request.get('/api/cash')).json()).balance).toBe(cash.balance);
  expect((await (await page.request.get(`/api/plants/${plant.id}`)).json()).stock_quantity).toBe(5);
  await leaveStore(page);
  expect((await state(page)).delivery?.activeOrderId).toBe(order.id);
  await expect(page.locator('#btn-start-delivery-route')).toBeVisible();
  // Afasta-se para rearmar a porta antes de testar a reentrada.
  await holdKeys(page, ['ArrowDown'], 400);
  await enterStore(page);
  await teleport(page, PREP_BENCH.interact.x, PREP_BENCH.interact.y);
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().delivery?.interior?.nearPrep);
  expect((await state(page)).delivery?.interior?.carrying).toBe(true);
  const again = (await state(page)).delivery!.interior!.promptBounds!;
  expect(again.x + again.width).toBeLessThanOrEqual((await state(page)).camera!.width + 1);
});
