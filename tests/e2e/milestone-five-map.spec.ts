import { expect, test } from '@playwright/test';
import { login } from './helpers';
import { closeSuiteOrders, createSuiteOrder, suiteId } from './suiteData';

test('P01/P02: mapa aguarda confirmação, conserva dados na falha e retenta sem venda duplicada', async ({ page }) => {
  await login(page);
  await closeSuiteOrders(page);
  const plant = await (await page.request.post('/api/plants', { data: { id: suiteId('m5map'), name: 'Planta para mapa', price: 20, stock_quantity: 5, image_path: '/pwa-192x192.png' } })).json();
  const order = await createSuiteOrder(page, { plantId: plant.id, quantity: 2, customerName: 'Cliente do mapa' });
  await page.request.put(`/api/orders/${order.id}`, { data: { status: 'pronto' } });
  await page.request.put(`/api/plants/${plant.id}`, { data: { name: plant.name, price: 99, stock_quantity: 5 } });
  const before = await (await page.request.get('/api/cash')).json();
  await page.reload();
  await page.locator('#tab-btn-orders').click();
  await page.locator(`#order-card-${order.id}`).getByRole('button', { name: 'Ou ver rota no Mapa Clássico' }).click();
  const pattern = /\/api\/deliveries\/[^/]+\/finish$/;
  await page.route(pattern, route => route.fulfill({ status: 503, json: { error: 'Entrega indisponível no teste. Tente novamente.' } }));
  await page.locator('#btn-confirm-delivery').click();
  await expect(page.getByRole('alert')).toContainText('Entrega indisponível');
  await expect(page.getByText(/adicionados ao Caixa Virtual da Loja/)).toHaveCount(0);
  expect((await (await page.request.get(`/api/plants/${plant.id}`)).json()).stock_quantity).toBe(5);
  expect((await (await page.request.get('/api/cash')).json()).balance).toBe(before.balance);
  await page.unroute(pattern);
  let release!: () => void;
  const gate = new Promise<void>(resolve => { release = resolve; });
  let calls = 0;
  await page.route(pattern, async route => { calls++; await gate; await route.continue(); });
  await page.locator('#btn-confirm-delivery').click();
  await expect(page.locator('#btn-confirm-delivery')).toBeDisabled();
  await expect(page.getByText(/adicionados ao Caixa Virtual da Loja/)).toHaveCount(0);
  expect((await (await page.request.get('/api/cash')).json()).balance).toBe(before.balance);
  release();
  await expect(page.getByText(/40,00 adicionados ao Caixa Virtual da Loja/)).toBeVisible();
  const after = await (await page.request.get('/api/cash')).json();
  expect(calls).toBe(1);
  expect(after.balance).toBe(before.balance + 40);
  expect(after.transactions.filter((t: any) => t.order_id === order.id)).toHaveLength(1);
  expect((await (await page.request.get(`/api/plants/${plant.id}`)).json()).stock_quantity).toBe(3);
});
