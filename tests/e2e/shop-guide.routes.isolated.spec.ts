import { expect, test } from '@playwright/test';
import { closeSuiteOrders, createSuiteOrder, suiteId } from './suiteData';
import { enterStore, leaveStore, login, openAdventure, state, teleport, waitForScene } from './helpers';
import { WORLD_MAP } from '../../src/phaser-game/config/worldMap';
import { HOUSE_CATALOG } from '../../src/phaser-game/config/houseCatalog';
import { COUNTER } from '../../src/phaser-game/config/interiorMap';

test.use({ viewport: { width: 480, height: 500 }, hasTouch: true });
test('entrega → orientação às utilidades → compra → orientação à Novo Hiper → instalação', async ({ page }) => {
  test.setTimeout(120_000);
  await login(page); await closeSuiteOrders(page);
  const plant = await (await page.request.post('/api/plants', { data: { id: suiteId('guide'), name: 'Planta do caminho', price: 150, stock_quantity: 5, image_path: '/pwa-192x192.png' } })).json();
  const order = await createSuiteOrder(page, { plantId: plant.id, destination: 'bairro1/house_007' });
  expect((await page.request.post('/api/deliveries/start', { data: { order_id: order.id } })).ok()).toBe(true);
  await openAdventure(page); await page.locator('#btn-adventure-fullscreen').click();
  await page.waitForFunction(() => Boolean(document.fullscreenElement));
  await page.waitForFunction(id => window.__NH_ADVENTURE__?.getState().delivery?.activeOrderId === id, order.id);
  const house = HOUSE_CATALOG.find(h => h.destinationId === order.destination_id)!;
  await teleport(page, house.deliveryPoint.x, house.deliveryPoint.y);
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().delivery?.near);
  await page.keyboard.press('KeyE');
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().delivery?.phase === 'done');
  await page.locator('#btn-guide-utilities').click();
  const start = (await state(page)).player!;
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().delivery?.indicator?.name === 'Loja de Utilidades');
  expect(Math.hypot((await state(page)).player!.x - start.x, (await state(page)).player!.y - start.y)).toBeLessThan(5);
  await page.screenshot({ path: 'docs/evidence/shop-guide/volta-as-utilidades.png' });
  await page.locator('#btn-cancel-shop-guide').click();
  await expect(page.locator('#story-guidance')).not.toContainText('Siga a seta');
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().delivery?.phase === 'idle');
  await page.locator('#btn-guide-utilities').click();
  const cash = await (await page.request.get('/api/cash')).json();
  await teleport(page, WORLD_MAP.utilities.interact.x, WORLD_MAP.utilities.interact.y);
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().delivery?.shop.nearUtilities);
  await page.keyboard.press('KeyE');
  await expect(page.locator('#shop-panel')).toBeVisible();
  const shop = await (await page.request.get('/api/shop')).json();
  const upgrade = shop.upgrades.find((u: any) => u.state === 'available');
  expect(upgrade).toBeTruthy();
  await page.locator(`#btn-shop-buy-${upgrade.id}`).click();
  await expect(page.locator('#btn-shop-guide-store')).toBeVisible();
  await page.locator('#btn-shop-guide-store').click();
  await expect(page.locator('#shop-panel')).toHaveCount(0);
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().delivery?.indicator?.name === 'Novo Hiper');
  await expect(page.locator('#story-guidance')).toContainText('instale sua melhoria');
  expect((await (await page.request.get('/api/cash')).json()).balance).toBe(cash.balance - upgrade.price);
  await page.screenshot({ path: 'docs/evidence/shop-guide/volta-para-instalar.png' });
  await enterStore(page); await waitForScene(page, 'interior');
  await teleport(page, COUNTER.interact.x, COUNTER.interact.y);
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().delivery?.interior?.nearCounter);
  await page.keyboard.press('KeyE');
  await expect(page.locator('#shop-panel')).toBeVisible();
  await page.locator(`#btn-shop-install-${upgrade.id}`).click();
  await expect(page.locator('#shop-panel')).toHaveCount(0);
  // Outras suítes podem ter concluído o arco; reconhece esse aviso no banco descartável.
  const progress = await (await page.request.get('/api/progress')).json();
  if (progress.milestones.bairro_vivo?.achievedAt) {
    await page.request.post('/api/progress/celebrations/bairro_vivo/ack');
    await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  }
  await leaveStore(page);
  await expect(page.locator('#story-guidance')).not.toContainText('Siga a seta');
  expect((await (await page.request.get('/api/shop')).json()).upgrades.find((u: any) => u.id === upgrade.id).state).toBe('installed');
  expect((await (await page.request.get('/api/cash')).json()).balance).toBe(cash.balance - upgrade.price);
});

test('cancelar restaura o cliente; abandonar a plataforma preserva pedido e estoque', async ({ page }) => {
  test.setTimeout(90_000);
  await login(page); await closeSuiteOrders(page);
  const plant = await (await page.request.post('/api/plants', { data: { id: suiteId('guide-active'), name: 'Planta do pedido ativo', price: 20, stock_quantity: 5, image_path: '/pwa-192x192.png' } })).json();
  await openAdventure(page); await page.locator('#btn-adventure-fullscreen').click();
  await page.waitForFunction(() => Boolean(document.fullscreenElement));
  const guideButton = page.locator('#btn-guide-utilities, #btn-guide-store').first();
  const guideName = await guideButton.getAttribute('id') === 'btn-guide-store' ? 'Novo Hiper' : 'Loja de Utilidades';
  await guideButton.click();
  const order = await createSuiteOrder(page, { plantId: plant.id, customerName: 'Cliente preservado', destination: 'bairro1/house_007' });
  await page.request.post('/api/deliveries/start', { data: { order_id: order.id } });
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await page.waitForFunction(id => window.__NH_ADVENTURE__?.getState().delivery?.activeOrderId === id, order.id);
  await page.waitForFunction(name => window.__NH_ADVENTURE__?.getState().delivery?.indicator?.name === name, guideName);
  const cash = await (await page.request.get('/api/cash')).json();
  await page.locator('#btn-cancel-shop-guide').click();
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().delivery?.indicator?.name === 'Cliente preservado');
  const { ENTRANCE_ZONE } = await import('../../src/phaser-game/config/worldConfig');
  await teleport(page, ENTRANCE_ZONE.x, ENTRANCE_ZONE.y);
  await waitForScene(page, 'platform');
  await page.locator('#btn-platform-exit').click(); await waitForScene(page, 'world');
  await page.waitForFunction(() => window.__NH_ADVENTURE__?.getState().delivery?.indicator?.name === 'Cliente preservado');
  expect((await state(page)).delivery?.activeOrderId).toBe(order.id);
  expect((await (await page.request.get('/api/cash')).json()).balance).toBe(cash.balance);
  expect((await (await page.request.get(`/api/plants/${plant.id}`)).json()).stock_quantity).toBe(5);
});
