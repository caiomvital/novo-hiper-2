import { afterEach, beforeEach, expect, it } from 'vitest';
import { startTestServer, type TestServer } from './helpers/testServer';
import { createPlant, createOrder, startDelivery, stockOf } from './helpers/builders';
let s: TestServer;
beforeEach(async () => { s = await startTestServer(); });
afterEach(async () => { await s.close(); });
const accept = '/api/progress/stories/cantinho_maria/accept';
const ack = '/api/progress/stories/cantinho_maria/ack';
const story = async () => (await s.get('/api/progress')).body.residentStory;
it('exige sessão; apenas aceitar e retirar não concluem jardim nem geram dinheiro', async () => {
  expect((await s.raw('POST', accept, { cookie: false })).status).toBe(401);
  expect((await s.post(ack)).status).toBe(409);
  expect((await story()).status).toBe('available');
  expect((await s.post(accept)).body.status).toBe('waiting');
  const p = await createPlant(s, { name: 'Planta escolhida da loja', price: 27.5, stock_quantity: 3 });
  const after = await story();
  expect(after.status).toBe('ordered');
  const o = (await s.get(`/api/orders/${after.orderId}`)).body;
  expect(o.customer_id).toBe('cust_dona_maria');
  expect(o.items[0].plant_id).toBe(p.id); expect(o.total).toBe(27.5);
  await startDelivery(s, o.id);
  expect((await story()).status).toBe('ordered');
  expect(await stockOf(s, p.id)).toBe(3);
  expect((await s.get('/api/cash')).body.balance).toBe(0);
});
it('reserva a próxima vaga sem substituir pedido ativo e espera reposição quando necessário', async () => {
  const p = await createPlant(s, { stock_quantity: 1 });
  const existing = await createOrder(s, [{ plant_id: p.id }]);
  const queued = await s.post(accept); expect(queued.body.status).toBe('waiting');
  expect((await s.get('/api/orders')).body).toHaveLength(1);
  const d = await startDelivery(s, existing.id); await s.post(`/api/deliveries/${d.id}/finish`);
  expect((await story()).status).toBe('waiting');
  await s.put(`/api/plants/${p.id}`, { name: p.name, price: p.price, stock_quantity: 2 });
  const next = await story(); expect(next.status).toBe('ordered');
  expect(next.orderId).not.toBe(existing.id);
  expect((await s.get(`/api/orders/${existing.id}`)).body.status).toBe('entregue');
  expect((await s.get('/api/orders')).body.filter((o: any) => o.status !== 'entregue')).toHaveLength(1);
});
it('conclui pela entrega oficial uma vez, preserva identidade e sobrevive a reinício e exclusão da planta', async () => {
  const p = await createPlant(s, { name: 'Minha Camomila', price: 42, stock_quantity: 3, image_path: '/uploads/plants/minha.png' });
  const accepted = (await s.post(accept)).body;
  expect((await s.post(accept)).body.orderId).toBe(accepted.orderId);
  expect((await s.get('/api/orders')).body).toHaveLength(1);
  const d = await startDelivery(s, accepted.orderId);
  expect((await s.post(`/api/deliveries/${d.id}/finish`)).status).toBe(200);
  expect((await story())).toMatchObject({ status: 'completed', plantName: 'Minha Camomila', plantPhotoUrl: '/uploads/plants/minha.png', acknowledged: false });
  await s.post(`/api/deliveries/${d.id}/finish`);
  expect(await stockOf(s, p.id)).toBe(2);
  const cash = (await s.get('/api/cash')).body; expect(cash.balance).toBe(42); expect(cash.transactions).toHaveLength(1);
  expect((await s.post(ack)).body.acknowledged).toBe(true);
  await s.post(ack); await s.post(accept);
  expect((await s.get('/api/cash')).body).toEqual(cash);
  expect((await s.get('/api/orders')).body).toHaveLength(1);
  await s.put(`/api/plants/${p.id}`, { name: 'Outro nome', price: 99, stock_quantity: 2 });
  await s.del(`/api/plants/${p.id}`);
  await s.restart();
  expect((await story())).toMatchObject({ status: 'completed', plantName: 'Minha Camomila', plantPhotoUrl: '/uploads/plants/minha.png', acknowledged: true });
  expect((await s.db.all('SELECT * FROM resident_stories'))).toHaveLength(1);
});
it('aceitações simultâneas e repetidas vinculam uma única encomenda', async () => {
  await createPlant(s);
  const responses = await Promise.all([s.post(accept), s.post(accept), s.post(accept)]);
  expect(responses.every(r => r.status === 200)).toBe(true);
  const ids = new Set(responses.map(r => r.body.orderId)); expect(ids.size).toBe(1);
  expect((await s.get('/api/orders')).body).toHaveLength(1);
  expect((await s.db.all('SELECT * FROM resident_stories'))).toHaveLength(1);
});
